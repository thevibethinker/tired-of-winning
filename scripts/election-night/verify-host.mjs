import assert from 'node:assert/strict';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { chromium } from '/root/agent-browser/node_modules/playwright-core/index.mjs';

const output = process.argv[2];
const base = 'http://localhost:51754';
if (!output?.startsWith('/')) throw new Error('Supply an absolute scratch evidence directory. Staging only.');
mkdirSync(output, { recursive: true });
const { key } = JSON.parse(readFileSync(new URL('../data/party-host-key.json', import.meta.url), 'utf8'));
const browser = await chromium.launch({ headless: true, args: ['--no-sandbox'] });
const guestContext = await browser.newContext({ viewport: { width: 390, height: 844 }, reducedMotion: 'reduce' });
const hostContext = await browser.newContext({ viewport: { width: 390, height: 844 }, reducedMotion: 'reduce' });
const guest = await guestContext.newPage(), host = await hostContext.newPage();
const checks = [], errors = [];
for (const p of [guest, host]) p.on('pageerror', e => errors.push(e.message));
const check = (name, pass) => { checks.push({ name, pass: Boolean(pass) }); assert.ok(pass, name); };
const api = (p, action, body) => p.evaluate(async ({ action, body }) => { const r = await fetch('/api/party/' + action, { method: 'POST', headers: { 'Content-Type': 'application/json', 'X-Party-Request': '1' }, body: JSON.stringify(body) }); return { status: r.status, body: await r.json() }; }, { action, body });
const get = p => p.evaluate(async () => (await fetch('/api/party')).json());
const open = async p => { await p.locator('.chat-button').click(); await p.locator('#party-handle').waitFor(); };
const close = p => p.keyboard.press('Escape');
const tag = String(Date.now()).slice(-8);
const first = `REHEARSAL HOST ${tag} — <img src=x onerror=alert(1)> 💙`;
const second = `REHEARSAL HOST ${tag} — a second take, for rotation.`;
const posted = [];
try {
  await Promise.all([guest.goto(base), host.goto(base)]);
  await Promise.all([guest.waitForSelector('.hero'), host.waitForSelector('.hero')]);
  await open(guest);
  await guest.waitForFunction(() => !document.querySelector('#party-message').disabled);
  await guest.getByLabel('What’s the room saying?').fill('DRAFT survives closing the sheet');
  await close(guest); await open(guest);
  check('draft survives closing and reopening the sheet', await guest.locator('#party-message').inputValue() === 'DRAFT survives closing the sheet');
  await guest.getByLabel('What’s the room saying?').fill(first);
  await guest.getByRole('button', { name: 'Post to the room', exact: true }).click();
  await guest.getByText('Posted.', { exact: true }).waitFor();
  posted.push((await get(guest)).comments.find(c => c.body === first).id);
  await close(guest);
  await host.waitForFunction(text => document.querySelector('.party-banner-copy')?.textContent.includes(text), first, { timeout: 12000 });
  check('a guest post automatically reaches the top banner', (await host.locator('.party-banner-copy').textContent()).includes(first));
  check('banner renders user text safely', await host.locator('.party-banner img').count() === 0);
  check('guests have no banner removal control', await guest.getByRole('button', { name: 'Remove displayed comment' }).count() === 0);
  await host.locator('.party-banner-message').click();
  check('banner opens the same comment in the single stream', await host.locator('.party-messages .is-highlighted').textContent().then(t => t.includes(first)));
  await host.getByText('Host controls', { exact: true }).click();
  await host.getByLabel('Private host key').fill('wrong');
  await host.getByRole('button', { name: 'Unlock', exact: true }).click();
  await host.getByRole('alert').waitFor();
  check('incorrect host key cannot unlock moderation', (await get(host)).isHost === false);
  await host.getByLabel('Private host key').fill(key);
  await host.getByRole('button', { name: 'Unlock', exact: true }).click();
  await host.getByText('Host controls unlocked', { exact: true }).waitFor();
  check('private key enables host controls', (await get(host)).isHost === true);
  check('host key is cleared from the page after login', await host.locator('#host-key').count() === 0 && !(await host.content()).includes(key));
  await host.getByLabel('Find a comment or handle').fill(tag);
  await host.locator('.party-messages li').first().waitFor();
  await host.waitForFunction(() => document.querySelector('.party-message-heading')?.textContent.includes('1 messages'));
  check('host can search the stream by comment text', await host.locator('.party-messages li').count() === 1);
  await host.getByRole('button', { name: /^Remove comment by/ }).click();
  await host.getByRole('button', { name: 'Undo removal', exact: true }).last().waitFor();
  await guest.waitForFunction(text => !document.querySelector('.party-banner-copy')?.textContent.includes(text), first, { timeout: 12000 });
  check('host removal clears the banner in another browser', !(await get(guest)).comments.some(c => c.body === first));
  await host.getByRole('button', { name: 'Undo removal', exact: true }).last().click();
  await guest.waitForFunction(text => document.querySelector('.party-banner-copy')?.textContent.includes(text), first, { timeout: 12000 });
  check('undo restores the same comment across browsers', (await get(guest)).comments.some(c => c.id === posted[0]));
  await host.getByRole('button', { name: 'Clear comment search' }).click();
  await host.reload(); await host.getByText('Host controls unlocked', { exact: true }).waitFor();
  check('host session survives page reload', (await get(host)).isHost === true);
  await close(host);
  const reply = await api(guest, 'comment', { body: second, requestId: 'host_rotation_' + tag });
  check('second comment posts successfully', reply.status === 200);
  posted.push(reply.body.comments.find(c => c.body === second).id);
  await host.getByRole('button', { name: 'Resume comment rotation' }).waitFor({ timeout: 12000 });
  check('reduced motion starts comment rotation paused', await host.getByRole('button', { name: 'Resume comment rotation' }).getAttribute('aria-pressed') === 'true');
  const old = await host.locator('.party-banner-copy').textContent();
  await host.getByRole('button', { name: 'Next comment' }).click();
  check('manual next changes the comment without animation', await host.locator('.party-banner-copy').textContent() !== old);
  await host.getByRole('button', { name: 'Resume comment rotation' }).click();
  await host.locator('.wordmark').focus(); await host.mouse.move(380, 500);
  const rotating = await host.locator('.party-banner-copy').textContent();
  await host.waitForFunction(text => document.querySelector('.party-banner-copy')?.textContent !== text, rotating, { timeout: 10000 });
  check('comments rotate automatically when resumed', true);
  await host.getByRole('button', { name: 'Pause comment rotation' }).click();
  const pausedText = await host.locator('.party-banner-copy').textContent();
  await host.locator('.wordmark').focus(); await host.mouse.move(380, 500); await host.waitForTimeout(8500);
  check('pause holds the displayed comment', await host.locator('.party-banner-copy').textContent() === pausedText);
  const removed = (await get(host)).comments.find(c => pausedText.includes(c.body));
  await host.getByRole('button', { name: 'Remove displayed comment' }).click();
  await host.getByRole('button', { name: 'Undo removal', exact: true }).waitFor();
  check('host can pull the displayed comment directly', !(await get(guest)).comments.some(c => c.id === removed.id));
  await host.getByRole('button', { name: 'Undo removal', exact: true }).click();
  await host.route('**/api/party', r => r.fulfill({ status: 503, contentType: 'application/json', body: JSON.stringify({ error: 'Synthetic outage' }) }));
  await host.getByText('Reconnecting to the room…', { exact: true }).waitFor({ timeout: 12000 });
  check('banner stops circulating stale comments during an outage', await host.locator('.party-banner-copy b').count() === 0);
  await host.unroute('**/api/party');
  await host.waitForFunction(() => document.querySelector('.party-banner-copy b'), null, { timeout: 12000 });
  check('banner recovers automatically', true);
  for (const width of [320, 390, 768, 1280]) {
    await host.setViewportSize({ width, height: 900 });
    check('banner fits at ' + width, await host.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
    await host.screenshot({ path: output + '/banner-' + width + '.png' });
    await open(host);
    check('host controls fit at ' + width, await host.evaluate(() => document.querySelector('dialog').scrollWidth <= document.querySelector('dialog').clientWidth));
    await host.screenshot({ path: output + '/host-' + width + '.png' });
    await close(host);
  }
  await guest.route('**/api/party', async r => { const response = await r.fetch(); const body = await response.json(); await r.fulfill({ json: { ...body, closed: true } }); });
  await open(guest);
  await guest.getByText('Read-only · the takes live on', { exact: true }).waitFor({ timeout: 12000 });
  check('the expired room disables posting', await guest.locator('#party-message').isDisabled());
  await api(host, 'moderate-comment', { id: posted[0], removed: true });
  await guest.waitForFunction(id => !document.getElementById('comment-' + id), posted[0], { timeout: 12000 });
  check('read-only viewers still receive host removals', await guest.locator('#comment-' + posted[0]).count() === 0);
  await guest.unroute('**/api/party');
  await open(host); await host.getByRole('button', { name: 'Lock host controls', exact: true }).click();
  await host.getByText('Host controls locked.', { exact: true }).waitFor();
  check('locking removes moderation privileges', (await api(host, 'moderate-comment', { id: posted[0], removed: true })).status === 403);
  check('no browser exceptions', errors.length === 0);
} finally {
  for (const id of posted) await api(guest, 'remove-comment', { id }).catch(() => {});
  await api(host, 'host-logout', {}).catch(() => {});
  writeFileSync(output + '/checks.json', JSON.stringify({ at: new Date().toISOString(), checks, errors }, null, 2));
  console.log(JSON.stringify({ passed: checks.filter(c => c.pass).length, total: checks.length, errors }));
  await browser.close();
}
